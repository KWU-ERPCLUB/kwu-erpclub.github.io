-- 정리(2026-08-19) — 공고 중복 제거. 오너 발견: 화면에 ADsP가 2건 뜬다.
--
-- 원인: 초기에 시드 SQL로 직접 넣은 행(키 = null)과, 지금 파이프라인이 넣는 행(키 = 있음)이
--       같은 공고를 각각 만들었다. 자동 동기화는 upsert만 하므로 옛 행을 지우지 못한다.
--       (같은 목적의 cleanup-2026-08-18.sql이 있었으나 실행되지 않았고, 제목이 완전히 일치해야만
--        잡히는 한계가 있어 이 파일로 대체한다.)
--
-- 실행 순서: ①번을 먼저 돌려 눈으로 확인 → ②번 실행 → ③번으로 결과 재확인.

-- ────────────────────────────────────────────────
-- ① 확인 — 키 없는 행(= 옛 수기·시드 등록분)을 전부 나열한다.
--    여기 나오는 것 중 "지금 목록에도 있는 것"이 중복이다.
-- ────────────────────────────────────────────────
select id, "제목", "종류", "분류", "접수마감", created_at
  from postings
 where "키" is null
 order by created_at;

-- ────────────────────────────────────────────────
-- ② 삭제 — 키 없는 행 중, 같은 공고가 키 있는 행으로도 존재하는 것만 지운다.
--    제목이 조금 달라도 잡히도록 핵심 토막(ADsP·SQLD 등)으로 대조한다.
--    수기로만 등록한 행(짝이 없는 것)은 건드리지 않는다.
-- ────────────────────────────────────────────────
delete from postings p
where p."키" is null
  and exists (
    select 1 from postings q
     where q."키" is not null
       and (
         q."제목" = p."제목"                                        -- 제목 완전 일치
         or (p."분류" is not null and q."분류" = p."분류"           -- 또는 같은 세부 분류 + 같은 종류
             and q."종류" = p."종류")
       )
  );

-- 학사일정도 같은 방식으로(날짜까지 같아야 지운다 — 날짜가 다르면 별개 일정이다)
delete from events e
where e."키" is null
  and exists (
    select 1 from events q
     where q."키" is not null and q."제목" = e."제목" and q."날짜" = e."날짜"
  );

-- ────────────────────────────────────────────────
-- ③ 재확인 — 같은 (종류, 분류) 조합이 2건 이상 남아 있으면 여기 뜬다.
--    남은 것이 진짜 별개 공고인지(예: ADsP 51회 / 52회) 눈으로 판단한다.
-- ────────────────────────────────────────────────
select "종류", "분류", count(*) as 건수, string_agg("제목", ' | ') as 제목들
  from postings
 group by "종류", "분류"
having count(*) > 1
 order by 건수 desc;
