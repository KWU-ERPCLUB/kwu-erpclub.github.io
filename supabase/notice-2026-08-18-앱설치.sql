-- 공지 등록(2026-08-18) — 허브 폰 설치(PWA) 안내. 워크스페이스 홈 > 공지에 노출(내부 공지).
-- 적용 = Supabase SQL 에디터에서 1회 실행. 재실행 안전(같은 제목이 있으면 건너뜀).

insert into notices (제목, 본문, 내부여부)
select
  '허브를 폰에서 앱처럼 쓰는 법',
  E'허브를 홈 화면에 추가하면 앱처럼 전체 화면으로 열린다. 앱스토어 설치·비용 없음.\n\n'
  || E'- 아이폰 = **사파리**로 접속 → 공유 버튼 → **홈 화면에 추가** (아이폰의 크롬 앱에서는 안 됨)\n'
  || E'- 갤럭시(크롬) = 우상단 ⋮ 메뉴 → **홈 화면에 추가**(기기에 따라 "앱 설치")\n'
  || E'- 갤럭시(삼성 인터넷) = 하단 ☰ 메뉴 → 현재 페이지 추가 → **홈 화면**\n\n'
  || E'설치 후 홈 화면의 AIM 아이콘으로 열면 로그인 화면부터 시작한다.',
  true
where not exists (select 1 from notices where 제목 = '허브를 폰에서 앱처럼 쓰는 법');
