// 기고 1트랙 형식 단일원천 — 구분자·필드 정의 + 프롬프트 키트 문안.
// 파서(contrib-parser.js)와 키트가 이 상수를 공유한다(spec 2026-08-05-기고-투트랙 §1-2 — 이중 원천 금지).
// 성격·주제 허용값은 schema.js에서 동적으로 끼워 넣는다(하드코딩 금지).
import { NATURES, TOPICS } from '../content/schema.js'

// 구분자 = 행 단독 `===필드명===` (spec §1-3). 필드 7종 — 순서 = 키트 출력 순서.
export const FIELD_NAMES = ['제목', '설명', '성격', '주제', '출처링크', '출처이름', '본문']

export function delimOf(name) {
  return `===${name}===`
}

// 파서 결과 → 기고 폼 상태 키 매핑(출처 2필드만 영문 키 — Contribute.jsx EMPTY와 동일).
export const FIELD_TO_DRAFT = {
  제목: '제목',
  설명: '설명',
  성격: '성격',
  주제: '주제',
  출처링크: 'source_url',
  출처이름: 'source_name',
  본문: '본문',
}

// 프롬프트 키트 문안 — [프롬프트 복사] 버튼이 이 문자열을 클립보드에 넣는다.
// 문체 기본값 = 개조식. 단 톤·문체는 멤버 재량(문안에 명시) — 키트는 형식만 고정한다.
export function buildPromptKit() {
  const guide = {
    제목: '글 제목 1줄',
    설명: '목록 카드에 표시될 핵심 1줄',
    성격: `다음 중 1개만 그대로 출력: ${NATURES.join(' | ')}`,
    주제: `다음 중 1개만 그대로 출력: ${TOPICS.join(' | ')}`,
    출처링크: '원문 URL 1개',
    출처이름: '매체·기관 이름',
    본문: '마크다운 본문',
  }
  const format = FIELD_NAMES.map((n) => `${delimOf(n)}\n${guide[n]}`).join('\n')
  return [
    'AIM(광운대 ERP연구회 산하 MIS·AI 스터디) 인사이트 기고 초안 작성 요청.',
    '',
    '[할 일]',
    '- 아래 소재 URL의 내용을 읽고 기고 초안 1건 작성',
    '- 소재 URL: (여기에 URL 붙여넣기)',
    '',
    '[출력 형식 — 구분자 7개를 아래 순서 그대로, 형식 밖 텍스트(인사말·부연) 금지]',
    format,
    '',
    '[작성 규칙]',
    '- 본문 수치·주장마다 출처 명시(본문 안 링크)',
    '- 문체 기본값 = 개조식·단문. 문체·톤은 작성자 재량 — 다른 문체를 원하면 이 줄을 고쳐 지시',
    '- 과장·감탄·권유형 수사 금지',
    '- 문단은 3문장 이하로 끊고 사이에 빈 줄',
  ].join('\n')
}
